/**
 * `icon` = clé `PRODUCT_LINK_FIELDS` — brand autopubliée si dispo, sinon
 * générique Phosphor (table PHOSPHOR ci-dessus). `className` dimensionne
 * (ex. `w-5 h-5`) et colore (currentColor, suit le thème).
 */
export function StoreLogo({ icon, className }: { icon: string; className?: string }) {
  const path = BRAND_PATHS[icon];
  if (path) return <BrandMark d={path} className={className} />;
  const PhosphorIcon = PHOSPHOR[icon] ?? Globe;
  return <PhosphorIcon weight="bold" className={className} />;
}
